import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import test from 'node:test';
import { Context } from '@deepseek-ai/cordis';
import { AgentRegistry } from '@deepseek-ai/dsh-agent';
import { LocalFileSystem } from '@deepseek-ai/dsh-fs-local';
import * as ObservationPolicy from '@deepseek-ai/dsh-fs-observation-policy';
import { SessionStore } from '@deepseek-ai/dsh-session';
import { SessionProjectionRegistry } from '@deepseek-ai/dsh-session-projection';
import { SystemPrompt } from '@deepseek-ai/dsh-system-prompt';
import * as ToolFS from '@deepseek-ai/dsh-tool-fs';
import { NativeToolExecutor } from '@deepseek-ai/dsh-tool-executor-native';
import { ToolRuntime } from '@deepseek-ai/dsh-tools';
import { WorkingDirectoryService } from '@deepseek-ai/dsh-working-directory';
import { registerDocumentSafety } from './document-safety.mjs';

test('real tool-fs observation and document safety preserve external edits', async t => {
  const home = await mkdtemp(join(tmpdir(),'synthetic-fs-'));
  const root = join(home,'workspace'), privateHome = join(home,'private');
  await mkdir(root); await mkdir(privateHome);
  const oldEnv = Object.fromEntries(['HARNESS_DOCUMENT_PROTECTION','HARNESS_USER_MODE','HARNESS_WORKSPACE','DSH_HOME'].map(key => [key,process.env[key]]));
  Object.assign(process.env,{HARNESS_DOCUMENT_PROTECTION:'true',HARNESS_USER_MODE:'false',HARNESS_WORKSPACE:root,DSH_HOME:privateHome});
  t.after(async () => { for (const [key,value] of Object.entries(oldEnv)) value === undefined ? delete process.env[key] : process.env[key]=value; await rm(home,{recursive:true,force:true}); });
  const path = join(root,'synthetic.md');
  const largePath = join(root,'synthetic-large.md'), largeText = 'Synthetic paragraph.\n'.repeat(700);
  await writeFile(path,'Synthetic original\nalpha\n');
  await writeFile(largePath,largeText);
  const ctx = new Context(); t.after(() => ctx.fiber.dispose());
  new SystemPrompt(ctx,{});
  const sessions = new SessionStore(ctx);
  await ctx.plugin(SessionProjectionRegistry);
  await ctx.plugin(AgentRegistry);
  new LocalFileSystem(ctx,{cwd:root,diffBasisMaxBytes:2<<20});
  await ctx.plugin(WorkingDirectoryService,{defaultDirectory:root});
  const tools = new ToolRuntime(ctx);
  tools.setExecutor(new NativeToolExecutor(ctx));
  const first = {ctx:new Context(),session:sessions.create('synthetic-first',{meta:{cwd:root}})}; first.id=first.session.id;
  const second = {ctx:new Context(),session:sessions.create('synthetic-second',{meta:{cwd:root}})}; second.id=second.session.id;
  const leaveFirst=ctx.agents.enter(first,undefined), leaveSecond=ctx.agents.enter(second,undefined);
  t.after(() => { leaveSecond(); leaveFirst(); });
  await ctx.plugin(ObservationPolicy);
  await ctx.plugin(ToolFS,{readImage:false,applyPatch:false});
  await ctx.plugin({inject:['systemPrompt','tools','fs'],apply:registerDocumentSafety});
  let sequence=0;
  async function execute(agent,name,args) {
    const result = await tools.execute({agent,signal:AbortSignal.timeout(3000),calls:[{type:'tool-call',id:`synthetic-${++sequence}`,name,arguments:JSON.stringify(args)}]});
    return result.results[0].result;
  }
  const edit = agent => execute(agent,'edit',{file_path:path,old_string:'alpha',new_string:'beta'});
  const beforeRead = await edit(first);
  assert.equal(beforeRead.isError,true);
  assert.match(JSON.stringify(beforeRead),/FS_NOT_OBSERVED|requires reading/i);
  assert.equal(await readFile(path,'utf8'),'Synthetic original\nalpha\n');
  assert.equal((await execute(first,'read',{file_path:path})).isError,false);
  const otherAgent = await edit(second);
  assert.equal(otherAgent.isError,true);
  assert.match(JSON.stringify(otherAgent),/FS_NOT_OBSERVED|requires reading/i);
  await writeFile(path,'Synthetic external change\nalpha\n');
  const stale = await edit(first);
  assert.equal(stale.isError,true);
  assert.match(JSON.stringify(stale),/FS_STALE_VERSION|changed since/i);
  assert.equal(await readFile(path,'utf8'),'Synthetic external change\nalpha\n');
  assert.equal((await execute(first,'read',{file_path:path})).isError,false);
  assert.equal((await edit(first)).isError,false);
  assert.equal(await readFile(path,'utf8'),'Synthetic external change\nbeta\n');
  const versions = await execute(first,'document_versions',{action:'list',path});
  assert.equal(versions.isError,false);
  const saved = JSON.parse(versions.content[0].text);
  assert.ok(saved.versions.length >= 2, 'document safety must retain the externally changed version');
  assert.equal((await execute(first,'read',{file_path:largePath})).isError,false);
  const truncate = await execute(first,'write',{file_path:largePath,content:'Synthetic truncated output'});
  assert.equal(truncate.isError,true);
  assert.match(JSON.stringify(truncate),/protected_document_truncation/);
  assert.equal(await readFile(largePath,'utf8'),largeText);
});
