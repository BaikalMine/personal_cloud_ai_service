const { chromium } = require('/opt/ai-gateway-ui-tests/node_modules/playwright');
const fs = require('node:fs/promises');

(async () => {
  const browser = await chromium.launch({ headless: true, args: ['--no-sandbox'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.on('pageerror', error => console.log('PAGE ERROR', error.message));
  await page.goto('http://gateway-fixture:3089/harness/');
  await page.waitForTimeout(4000);
  const notice = page.getByRole('button', { name: 'Continue', exact: true });
  if (await notice.isVisible()) await notice.click();
  await page.locator('input[type=file]').setInputFiles({name:'verification-note.txt',mimeType:'text/plain',buffer:Buffer.from('Harness isolated attachment verification.')});
  await page.locator('[data-composer-input=true]').fill('Read the attached verification-note.txt and confirm receipt.');
  await page.getByRole('button', { name: 'Send message', exact: true }).click();
  await page.getByText('Harness file verification complete.', { exact: true }).waitFor({timeout:45000});
  await page.reload();
  await page.getByText('Harness file verification complete.', { exact: true }).waitFor({timeout:15000});
  console.log('FILE SEND AND SESSION RELOAD PASSED');
  await page.locator('[data-composer-input=true]').fill('cancel-fixture');
  await page.getByRole('button', { name: 'Send message', exact: true }).click();
  await page.waitForTimeout(1500);
  await page.getByRole('button', { name: 'Stop generating', exact: true }).click();
  await page.getByRole('button', { name: 'Send message', exact: true }).waitFor({timeout:10000});
  const metrics = await (await page.request.get('http://harness-fixture:3099/metrics')).json();
  if (!metrics.fileSeen || !metrics.cancelled) throw new Error('Attachment/cancellation fixture assertions failed');
  console.log('CANCELLATION PASSED', metrics);
  await page.screenshot({ path: '/qa/harness-desktop.png', fullPage: true });
  await page.setViewportSize({width:390,height:844});
  await page.waitForTimeout(500);
  await page.screenshot({path:'/qa/harness-mobile.png',fullPage:true});
  const sizing = await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));
  if (sizing.scroll > sizing.width) throw new Error('Mobile page overflows horizontally');
  console.log('MOBILE LAYOUT PASSED', sizing);
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('[data-composer-input=true]').fill('tool-fixture: run printf harness-tool-verification in bash');
  await page.getByRole('button',{name:'Send message',exact:true}).click();
  await page.getByText('Harness tool verification complete.',{exact:true}).waitFor({timeout:30000});
  const toolMetrics = await (await page.request.get('http://harness-fixture:3099/metrics')).json();
  if (!toolMetrics.toolResultSeen) throw new Error('Tool execution did not return a verified result');
  console.log('WORKSPACE TOOL EXECUTION PASSED');
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
