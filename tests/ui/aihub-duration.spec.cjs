const { test, expect } = require("@playwright/test");
const { settlePage, chooseWorkflow } = require("./helpers.cjs");

test("AIHUB matches reference duration without changing manual values or other modes", async ({ page }, info) => {
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  let body;
  await page.route("**/generate/preview/video", route => route.fulfill({ status: 422, body: "synthetic duration fixture" }));
  await page.route("**/generate/upload/video", route => route.fulfill({ json: { name: "duration.mp4", subfolder: "users/preview" } }));
  await page.route("**/generate/preflight", route => {
    body = new URLSearchParams(route.request().postData());
    return route.fulfill({ json: { ok: true, checks: [] } });
  });
  await page.goto("/preview/generate");
  await settlePage(page);
  await page.locator('[data-workflow-id="minimax-h3-video"]').click();
  await chooseWorkflow(page, "aihub-minimax-h3");
  await page.locator('[name="aihub_mode"][value="video"]').check();
  const toggle = page.locator("#aihub-match-duration");
  const manual = page.locator("#minimax-video-duration");
  await manual.fill("9");
  await toggle.check();
  await expect(manual).toBeHidden();
  await expect(manual).toBeDisabled();
  await page.locator("#minimax-video-file").setInputFiles({ name: "duration.mp4", mimeType: "video/mp4", buffer: Buffer.from("duration-fixture") });
  const metadata = seconds => page.locator("#minimax-video-preview-media").evaluate((video, value) => {
    Object.defineProperty(video, "duration", { configurable: true, value });
    video.dispatchEvent(new Event("loadedmetadata"));
  }, seconds);
  await metadata(7.608667);
  await expect(page.locator("#aihub-duration-status")).toContainText("7,609");
  await page.locator("#positive-prompt").fill("Ocean waves move slowly.");
  await page.locator("#generation-preflight-button").click();
  await expect.poll(() => body?.get("aihub_match_duration")).toBe("true");
  expect(body.get("aihub_output_frames")).toBeNull();
  expect(body.get("video_duration_seconds")).toBeNull();
  await toggle.scrollIntoViewIfNeeded();
  await page.screenshot({ path: info.outputPath("reference-duration.png") });
  await metadata(30);
  expect(await toggle.evaluate(input => input.validity.valid)).toBe(true);
  await metadata(30.1);
  expect(await toggle.evaluate(input => input.validity.valid)).toBe(false);
  await toggle.uncheck();
  await expect(manual).toBeVisible();
  await expect(manual).toHaveValue("9");
  expect(await toggle.evaluate(input => input.validity.valid)).toBe(true);
  await toggle.check();
  await page.locator('[name="aihub_mode"][value="carousel"]').check();
  await expect(toggle).toBeHidden();
  await expect(toggle).toBeDisabled();
  await expect(manual).toBeVisible();
  await page.locator('.aihub-advanced > summary').click();
  await page.locator('[name="aihub_carousel_pipeline"]').selectOption('legacy');
  await expect(manual).toBeHidden();
  await page.locator('[name="aihub_mode"][value="photo"]').check();
  await expect(manual).toBeVisible();
  await page.locator('[name="aihub_mode"][value="video"]').check();
  await metadata(7.608667);
  await expect(toggle).toBeChecked();
  await expect(manual).toBeHidden();
  await chooseWorkflow(page, "minimax-h3-video");
  await expect(manual).toBeVisible();
  await expect(manual).toBeEnabled();
  await expect(manual).toHaveValue("9");
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
  expect(errors).toEqual([]);
});
