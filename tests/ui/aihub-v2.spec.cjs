const { test, expect } = require('@playwright/test');
const { settlePage, chooseWorkflow } = require('./helpers.cjs');

test('AIHUB V2 photo source has sequential refinement controls and correct payload', async ({ page }, info) => {
  let body, assistant;
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/generate/preflight', route => {
    body = new URLSearchParams(route.request().postData());
    return route.fulfill({ json: { ok: true, checks: [] } });
  });
  await page.route('**/generate/prompt-assistant/jobs', route => {
    assistant = new URLSearchParams(route.request().postData());
    return route.fulfill({ json: { id: assistant.get('request_id'), state: 'completed', context: assistant.get('context'), original: assistant.get('prompt'), result: { prompt: 'An adult woman turns toward the camera.', model: 'fixture' } } });
  });
  await page.goto('/preview/generate'); await settlePage(page);
  await page.locator('[data-workflow-id="minimax-h3-video"]').click();
  await chooseWorkflow(page, "aihub-minimax-h3");
  await page.locator('[name="aihub_mode"][value="carousel"]').check();
  await page.locator('.aihub-advanced > summary').click();
  await expect(page.locator('[name="aihub_carousel_pipeline"]')).toHaveValue('v2');
  await expect(page.locator('[name="aihub_carousel_refiner"]')).toHaveValue('flux');
  await page.locator('[name="aihub_carousel_refiner"]').selectOption('qwen21');
  await page.locator('[name="aihub_carousel_source"]').selectOption('prompt');
  await page.locator('[name="aihub_photo_count"]').fill('2');
  await expect(page.locator('#minimax-video-reference')).toBeHidden();
  await expect(page.locator('[name="aihub_photo_stride"]')).toBeDisabled();
  await expect(page.locator('[name="aihub_latent_scale"]')).toBeDisabled();
  await expect(page.locator('[name="video_duration_seconds"]')).toBeEnabled();
  await expect(page.locator('[name="video_rtx_enabled"]')).toBeDisabled();
  await expect(page.locator('[name="aihub_dlss_enabled"]')).toBeDisabled();
  await page.locator('[data-image-slot="1"] [data-gallery-image-picker-open]').click();
  await page.getByRole('button', { name: 'Выбрать AI-Gateway-Krea2-product.png', exact: true }).click();
  await page.locator('#positive-prompt').fill('An adult woman smiles and turns toward the camera.');
  await page.locator('#generation-preflight-button').click();
  await expect.poll(() => body?.get('aihub_carousel_source')).toBe('prompt');
  expect(body.get('aihub_carousel_pipeline')).toBe('v2');
  expect(body.get('aihub_carousel_refiner')).toBe('qwen21');
  expect(body.get('aihub_photo_count')).toBe('2');
  expect(body.get('input_video') || '').toBe('');
  expect(body.get('aihub_latent_scale')).toBeNull();
  await page.locator('#prompt-assistant-open').click();
  await page.locator('#prompt-assistant-improve').click();
  await expect.poll(() => assistant?.get('aihub_carousel_source')).toBe('prompt');
  expect(assistant.get('aihub_carousel_refiner')).toBe('qwen21');
  expect(assistant.get('input_video') || '').toBe('');
  await page.locator('#prompt-assistant-close').click();
  await page.locator('.aihub-advanced').scrollIntoViewIfNeeded();
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
  await page.screenshot({ path: info.outputPath('aihub-v2-carousel.png'), fullPage: true });
  await page.locator('[name="aihub_carousel_source"]').selectOption('video');
  await expect(page.locator('#minimax-video-reference')).toBeVisible();
  await page.locator('[name="aihub_carousel_pipeline"]').selectOption('legacy');
  await expect(page.locator('[name="aihub_photo_stride"]')).toBeEnabled();
  await expect(page.locator('[name="aihub_photo_count"]')).toBeDisabled();
  await expect(page.locator('[name="aihub_carousel_refiner"]')).toBeDisabled();
  await page.locator('[name="aihub_carousel_pipeline"]').selectOption('v2');
  await expect(page.locator('[name="aihub_carousel_refiner"]')).toHaveValue('qwen21');
  await page.locator('.studio-saved > summary').click();
  await page.locator('#generation-draft-save').click();
  await expect(page.locator('#generation-draft-status')).toHaveText('Сохранено');
  await page.reload();
  await settlePage(page);
  await expect(page.locator('[name="aihub_carousel_refiner"]')).toHaveValue('qwen21');
  expect(errors).toEqual([]);
});
