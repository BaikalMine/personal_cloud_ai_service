const { test, expect } = require('@playwright/test');
const { settlePage, chooseWorkflow } = require('./helpers.cjs');

test('DLSS frame rate is independent, saved, and video-only', async ({ page }, info) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/preview/generate');
  await settlePage(page);
  await page.locator('[data-workflow-id="minimax-h3-video"]').click();
  await chooseWorkflow(page, "aihub-minimax-h3");
  await page.locator('[name="aihub_mode"][value="photo"]').check();
  await page.locator('[data-studio-settings-target="processing"]').click();
  const toggle = page.locator('[name="aihub_fg_enabled"]');
  const fps = page.locator('[name="aihub_fg_multiplier"]');
  const values = () => page.locator('#generation-form').evaluate(form => Object.fromEntries(new FormData(form)));
  await expect(toggle).not.toBeChecked();
  await expect(fps).toBeHidden();
  await toggle.check();
  await expect(fps).toBeVisible();
  await expect(fps).toHaveValue('2');
  await fps.selectOption('3');
  await expect(page.locator('[name="aihub_dlss_enabled"]')).not.toBeChecked();
  expect((await values()).aihub_fg_multiplier).toBe('3');
  await toggle.scrollIntoViewIfNeeded();
  await page.screenshot({ path: info.outputPath('fg-controls.png') });
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
  await page.locator('#studio-settings-close').click();
  await page.locator('.studio-saved > summary').click();
  await page.locator('#generation-draft-save').click();
  await expect(page.locator('#generation-draft-status')).toHaveText('Сохранено');
  await page.reload();
  await settlePage(page);
  await expect(toggle).toBeChecked();
  await expect(fps).toHaveValue('3');
  await page.locator('[name="aihub_mode"][value="carousel"]').check();
  await expect(toggle).toBeDisabled();
  expect((await values()).aihub_fg_enabled).toBeUndefined();
  expect((await values()).aihub_fg_multiplier).toBeUndefined();
  await page.locator('[name="aihub_mode"][value="video"]').check();
  await expect(toggle).toBeEnabled();
  expect((await values()).aihub_fg_multiplier).toBe('3');
  await chooseWorkflow(page, "minimax-h3-video");
  await expect(toggle).toBeDisabled();
  expect((await values()).aihub_fg_enabled).toBeUndefined();
  expect(errors).toEqual([]);
});
